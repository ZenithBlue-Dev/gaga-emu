#!/usr/bin/env python3
"""Assembles Cores/bsnes/GagaIPL.s, GagaEmu's clean-room SPC700 boot program, into Cores/bsnes/GagaIPL.inc.

  spc700-asm.py            writes GagaIPL.inc
  spc700-asm.py --check    fails if GagaIPL.inc is not what GagaIPL.s assembles to

Only the instruction forms GagaIPL.s uses are known; anything else is an error.
"""
import os
import re
import sys

CORE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Cores", "bsnes")
SOURCE, OUTPUT = os.path.join(CORE, "GagaIPL.s"), os.path.join(CORE, "GagaIPL.inc")
BASE, SIZE = 0xFFC0, 64

N = r"\$([0-9A-Fa-f]+)"  # a hex number
L = r"([A-Za-z_]\w*)"    # a label
# (pattern, opcode, operand kinds in byte order): b = byte from a number group, r = branch to a label,
# w = little-endian word from a number group.
FORMS = [
    (rf"mov x, #{N}", 0xCD, "b"), (r"mov sp, x", 0xBD, ""), (rf"mov a, #{N}", 0xE8, "b"),
    (rf"mov y, #{N}", 0x8D, "b"), (r"mov \(x\), a", 0xC6, ""), (r"dec x", 0x1D, ""), (r"inc y", 0xFC, ""),
    (rf"inc {N}", 0xAB, "b"), (rf"mov {N}, #{N}", 0x8F, "21"), (rf"cmp {N}, #{N}", 0x78, "21"),
    (rf"movw ya, {N}", 0xBA, "b"), (rf"movw {N}, ya", 0xDA, "b"), (rf"mov y, {N}", 0xEB, "b"),
    (rf"mov a, {N}", 0xE4, "b"), (rf"mov {N}, y", 0xCB, "b"), (rf"cmp y, {N}", 0x7E, "b"),
    (rf"mov \[{N}\]\+y, a", 0xD7, "b"), (rf"jmp \[!{N}\+x\]", 0x1F, "w"),
    (rf"bne {L}", 0xD0, "r"), (rf"beq {L}", 0xF0, "r"), (rf"bpl {L}", 0x10, "r"), (rf"bra {L}", 0x2F, "r"),
]


def assemble(text):
    labels, out = {}, []
    for final in (False, True):  # pass 1 places labels, pass 2 emits with them
        out = []
        for number, raw in enumerate(text.splitlines(), 1):
            line = raw.split(";")[0].strip().lower()
            where = f"GagaIPL.s:{number}"
            label = re.match(rf"{L}:\s*(.*)", line)
            if label:
                labels[label.group(1)] = BASE + len(out)
                line = label.group(2)
            if not line:
                continue
            org = re.fullmatch(rf"\.org {N}", line)
            if org:
                target = int(org.group(1), 16) - BASE
                assert len(out) <= target, f"{where}: code overruns .org"
                out += [0] * (target - len(out))
                continue
            word = re.fullmatch(rf"\.word {L}", line)
            if word:
                value = labels.get(word.group(1), 0) if not final else labels[word.group(1)]
                out += [value & 0xFF, value >> 8]
                continue
            for pattern, opcode, kinds in FORMS:
                m = re.fullmatch(pattern, line)
                if m:
                    break
            else:
                sys.exit(f"{where}: unknown instruction: {line}")
            out.append(opcode)
            if kinds == "b":
                out.append(int(m.group(1), 16))
            elif kinds == "21":  # 8F and 78 take the immediate first, then the direct page address
                out += [int(m.group(2), 16), int(m.group(1), 16)]
            elif kinds == "w":
                value = int(m.group(1), 16)
                out += [value & 0xFF, value >> 8]
            elif kinds == "r":
                if not final:
                    out.append(0)
                    continue
                target = labels.get(m.group(1))
                assert target is not None, f"{where}: unknown label {m.group(1)}"
                offset = target - (BASE + len(out) + 1)
                assert -128 <= offset <= 127, f"{where}: branch out of range"
                out.append(offset & 0xFF)
    assert len(out) == SIZE, f"assembled {len(out)} bytes, the IPL is {SIZE}"
    assert out[-2] | out[-1] << 8 == labels["reset"], "reset vector does not point at reset"
    return bytes(out)


def render(code):
    rows = [", ".join(f"0x{b:02x}" for b in code[k:k + 16]) for k in range(0, len(code), 16)]
    return "// Generated by scripts/spc700-asm.py from GagaIPL.s. Do not edit.\n" + ",\n".join(rows) + "\n"


if __name__ == "__main__":
    with open(SOURCE) as f:
        text = render(assemble(f.read()))
    if sys.argv[1:] == ["--check"]:
        with open(OUTPUT) as f:
            sys.exit(0 if f.read() == text else "GagaIPL.inc is stale: run scripts/spc700-asm.py")
    elif sys.argv[1:]:
        sys.exit(__doc__)
    with open(OUTPUT, "w") as f:
        f.write(text)
