#!/usr/bin/env bash
# Writes build/core-set.yml, which project.yml includes, then runs xcodegen. A build links only the
# cores in GAGA_CORE_SET; each one must already be built by scripts/build-core.sh.
#
#   scripts/generate-project.sh                  every core in Cores/ except the non-commercial ones and vktest
#   GAGA_CORE_SET=sideload scripts/generate-project.sh  every core, for a free personal build only
#   GAGA_CORE_SET="mgba" scripts/generate-project.sh    only those core IDs, space separated
#
# A left-out core keeps a refusing stub in the registry and is hidden from CoreCatalog, and the app's
# no-JIT gate fails the build if its framework is embedded anyway. A core whose core.env sets
# CORE_NONCOMMERCIAL=1 has a licence that forbids commercial use (docs/03 section 5): it never enters an
# App Store or TestFlight build, which scripts/appstore_release.sh and scripts/nojit-gate.sh enforce.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"

known=() commercial=()
for env in Cores/*/core.env; do
    core=$(basename "$(dirname "$env")")
    known+=("$core")
    # vktest is a debug and test core: name it in GAGA_CORE_SET (or use sideload) to run its tests.
    [ "$core" = vktest ] || grep -qx 'CORE_NONCOMMERCIAL=1' "$env" || commercial+=("$core")
done
sideload_settings='' sideload_tests=''
case "${GAGA_CORE_SET:-}" in
    "") core_set=${commercial[*]} ;;
    sideload)
        core_set=${known[*]}
        # A free build: GAGA_SIDELOAD compiles out StoreKit, the paywall and every purchase path, and
        # nojit-gate.sh then refuses an app that still links StoreKit.
        sideload_settings='      GAGA_SIDELOAD: "1"
      SWIFT_ACTIVE_COMPILATION_CONDITIONS: $(inherited) GAGA_SIDELOAD
'
        sideload_tests='  GagaEmuTests:
    settings:
      SWIFT_ACTIVE_COMPILATION_CONDITIONS: $(inherited) GAGA_SIDELOAD
'
        ;;
    *) core_set=$GAGA_CORE_SET ;;
esac

dependencies='' defines=''
for core in $core_set; do
    if [ ! -f "Cores/$core/core.env" ]; then
        echo "GAGA_CORE_SET names an unknown core: $core. Known: ${known[*]}" >&2
        exit 2
    fi
    # shellcheck source=/dev/null
    framework=$(source "Cores/$core/core.env" && echo "$CORE_FRAMEWORK")
    if [ ! -d "build/cores/$framework.xcframework" ]; then
        echo "build/cores/$framework.xcframework is missing. Run: scripts/build-core.sh $core" >&2
        exit 1
    fi
    dependencies+="      - framework: build/cores/$framework.xcframework
        embed: true
"
    defines+="        - GAGA_HAS_$(tr '[:lower:]' '[:upper:]' <<<"$core")=1
"
    # shellcheck source=/dev/null
    [ "$(source "Cores/$core/core.env" && echo "${CORE_USES_MOLTENVK:-}")" != 1 ] || uses_moltenvk=1
done
# The layer-path cores share one MoltenVK.framework (docs/06 section 2.5). The app embeds it but does not
# link it, so a build without those cores carries no MoltenVK.
if [ -n "${uses_moltenvk:-}" ]; then
    if [ ! -d build/moltenvk/dynamic/MoltenVK.xcframework ]; then
        echo "build/moltenvk/dynamic/MoltenVK.xcframework is missing. Run: scripts/build-moltenvk.sh" >&2
        exit 1
    fi
    dependencies+="      - framework: build/moltenvk/dynamic/MoltenVK.xcframework
        embed: true
        link: false
"
fi

# The GagaCheevos target (RetroAchievements) compiles this submodule in every build.
if [ ! -f Vendor/rcheevos/src/rc_client.c ]; then
    echo "rcheevos is missing. Run: git submodule update --init Vendor/rcheevos" >&2
    exit 1
fi
# The GagaSlang target (.slangp import) compiles glslang and SPIRV-Cross from these submodules in every build.
if [ ! -f Cores/flycast/deps/glslang/SPIRV/GlslangToSpv.cpp ] || [ ! -f Cores/ppsspp/upstream/ext/SPIRV-Cross/spirv_msl.cpp ]; then
    echo "glslang or SPIRV-Cross is missing. Run: git submodule update --init Cores/flycast/deps/glslang Cores/ppsspp/upstream && git -C Cores/ppsspp/upstream submodule update --init ext/SPIRV-Cross" >&2
    exit 1
fi

mkdir -p build
cat >build/core-set.yml <<YAML
# Generated by scripts/generate-project.sh. Do not edit.
targets:
  GagaEmu:
    dependencies:
$dependencies    settings:
      GAGA_CORE_SET: "$core_set"
$sideload_settings      GCC_PREPROCESSOR_DEFINITIONS:
        - \$(inherited)
$defines$sideload_tests
YAML
xcodegen generate
echo "core set: $core_set"
