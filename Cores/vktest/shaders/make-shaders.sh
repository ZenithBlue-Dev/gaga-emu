#!/usr/bin/env bash
# Assembles the test core's two shaders into ../VkTestShaders.h. Needs spirv-as and spirv-val from
# SPIRV-Tools (Homebrew spirv-tools). The build does not run this: the header is committed.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
out="$here/../VkTestShaders.h"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

{
    echo "// Generated by Cores/vktest/shaders/make-shaders.sh from the .spvasm files beside it. Do not edit."
    echo "#include <stdint.h>"
    for stage in vert frag; do
        spirv-as --target-env vulkan1.0 "$here/triangle.$stage.spvasm" -o "$tmp/$stage.spv"
        spirv-val --target-env vulkan1.0 "$tmp/$stage.spv"
        echo "static const uint32_t vt_${stage}_spirv[] = {"
        od -An -v -tx4 "$tmp/$stage.spv" | awk '{ line = "   "; for (i = 1; i <= NF; i++) line = line " 0x" $i ","; print line }'
        echo "};"
    done
} >"$out"
echo "wrote $out"
